#!/usr/bin/env bash
# Write deploy/compose/.env with random, local-only secrets (once; never overwrites a
# value, never prints one). Delete the file to regenerate. An existing file only gains
# the keys added since it was written.
#
# Nothing here is a provider key: the starter catalogue runs on the stubs container,
# and real provider keys are added by an admin in /admin (stored encrypted with
# GW_CREDENTIALS_KEY).
set -euo pipefail
f="$(cd "$(dirname "$0")/.." && pwd)/deploy/compose/.env"
rand() { openssl rand -base64 64 | tr -d '/+=\n' | cut -c1-"$1"; }
# 32 random bytes, standard base64 (TOTP_ENCRYPTION_KEY's and CREDENTIALS_KEY's format).
key32() { openssl rand -base64 32 | tr -d '\n'; }
umask 077

# key=generator pairs, in file order.
KEYS=(
  "GW_JWT_SECRET=rand 64"
  "GW_REFRESH_SECRET=rand 64"
  "GW_TOTP_ENCRYPTION_KEY=key32"
  "GW_CREDENTIALS_KEY=key32"
  "GW_API_KEY_PEPPER=rand 48"
  "GW_DEMO_PASSWORD=demo"
)

value() {
  case "$1" in
    demo) printf 'Demo-%s' "$(rand 12)" ;;
    key32) key32 ;;
    rand*) rand "${1#rand }" ;;
  esac
}

if [[ ! -f "$f" ]]; then
  printf '# Generated by scripts/gen-local-env.sh. Local only; never commit.\n' >"$f"
  fresh=1
else
  fresh=0
fi

added=()
for entry in "${KEYS[@]}"; do
  key="${entry%%=*}"
  gen="${entry#*=}"
  if ! grep -q "^${key}=" "$f"; then
    printf '%s=%s\n' "$key" "$(value "$gen")" >>"$f"
    added+=("$key")
  fi
done

if ((fresh)); then
  echo "wrote deploy/compose/.env"
elif ((${#added[@]})); then
  echo "deploy/compose/.env: added ${added[*]}"
else
  echo "deploy/compose/.env exists (delete it to regenerate)"
fi
